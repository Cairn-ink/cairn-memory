// The plugin is distributed on its own: no runtime import may escape its root.
import { mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { join } from 'node:path';

const source = fileURLToPath(new URL('./', import.meta.url));
const destination = fileURLToPath(new URL('../../plugins/cairn-memory/lib/', import.meta.url));
export const GENERATED_BANNER = '// Generated by integrations/client/bundle.mjs. Do not edit.\n';
// CX-3 adds disabled client building blocks. CX-4/LAC own their installed wiring
// and plugin bundle publication; preserve the released Claude module inventory.
export const DEFERRED_CLIENT_MODULES = Object.freeze([
  'common-profile.mjs', 'runtime-usage.mjs', 'state-lock.mjs',
]);
export const CLIENT_MODULES = Object.freeze({
  'capture-cursor.mjs': 'capture-cursor.mjs',
  'hosted-contract.mjs': 'hosted-contract.mjs',
  'hosted-schemas.mjs': 'hosted-schemas.mjs',
  'config.mjs': 'config.mjs',
  'control-state.mjs': 'control-state.mjs',
  'file-lock.mjs': 'file-lock.mjs',
  'identity.mjs': 'identity.mjs',
  'pairing.mjs': 'pairing.mjs',
  'private-state.mjs': 'private-state.mjs',
  'recall-query.mjs': 'recall-query.mjs',
  'redact.mjs': 'redact.mjs',
  'transport-hosted.mjs': 'http.mjs',
});

export const HOSTED_SCHEMA_NAMES = Object.freeze([
  'capture-request', 'capture-response', 'recall-response',
  'session-start-request', 'session-start-response', 'pause-state',
]);
export async function schemaModule() {
  const schemas = {};
  for (const name of HOSTED_SCHEMA_NAMES) {
    schemas[name] = JSON.parse(await readFile(
      new URL(`../../schemas/${name}.schema.json`, import.meta.url), 'utf8'));
  }
  return '// Frozen from schemas/ by integrations/client/bundle.mjs. Do not edit.\n' +
    'export const HOSTED_SCHEMAS = ' + JSON.stringify(schemas, null, 2) + ';\n';
}
export async function bundleClient({ check = false, target = destination } = {}) {
  const schemas = await schemaModule();
  const schemaPath = join(source, 'hosted-schemas.mjs');
  if (check) {
    if (await readFile(schemaPath, 'utf8') !== schemas) throw new Error('hosted_schemas_stale');
  } else await writeFile(schemaPath, schemas);
  const names = (await readdir(source)).filter(name => name.endsWith('.mjs') && name !== 'bundle.mjs').sort();
  if (JSON.stringify(names) !== JSON.stringify([...Object.keys(CLIENT_MODULES), ...DEFERRED_CLIENT_MODULES].sort())) {
    throw new Error('client_bundle_module_map_mismatch');
  }
  let existing;
  try { existing = await readdir(target, { withFileTypes: true }); }
  catch (error) { if (error.code !== 'ENOENT') throw error; existing = []; }
  // This directory also contains host-owned modules. Reconcile only files that
  // carry our ownership banner; never remove or rewrite unrelated plugin code.
  const unexpected = [];
  for (const entry of existing) {
    if (!entry.isFile() || !entry.name.endsWith('.mjs') || Object.values(CLIENT_MODULES).includes(entry.name)) continue;
    if ((await readFile(join(target, entry.name), 'utf8')).startsWith(GENERATED_BANNER)) unexpected.push(entry.name);
  }
  if (check && unexpected.length) throw new Error(`client_bundle_extra: ${unexpected.join(', ')}`);
  if (!check) {
    await mkdir(target, { recursive: true });
    for (const name of unexpected) await rm(join(target, name));
  }
  for (const name of Object.keys(CLIENT_MODULES).sort()) {
    const output = CLIENT_MODULES[name];
    const expected = Buffer.concat([Buffer.from(GENERATED_BANNER), await readFile(join(source, name))]);
    if (check) {
      let actual;
      try { actual = await readFile(join(target, output)); }
      catch (error) { if (error.code !== 'ENOENT') throw error; }
      if (!actual?.equals(expected)) throw new Error(`client_bundle_stale: ${output}; run node integrations/client/bundle.mjs`);
    } else await writeFile(join(target, output), expected);
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    if (process.argv.slice(2).some(arg => arg !== '--check')) throw new Error('unexpected_arguments');
    await bundleClient({ check: process.argv.includes('--check') });
    console.log('Client bundle matches shared source.');
  } catch (error) { console.error(error.message); process.exitCode = 1; }
}
