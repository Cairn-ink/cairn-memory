// The plugin is distributed on its own: no runtime import may escape its root.
import { mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { join } from 'node:path';

const source = fileURLToPath(new URL('./', import.meta.url));
const destination = fileURLToPath(new URL('../../plugins/cairn-memory/lib/client/', import.meta.url));
const banner = '// Generated by integrations/client/bundle.mjs. Do not edit.\n';

export async function bundleClient({ check = false, target = destination } = {}) {
  // Top-level .mjs files are runtime modules except this build-time generator.
  const names = (await readdir(source)).filter(name => name.endsWith('.mjs') && name !== 'bundle.mjs').sort();
  let existing;
  try { existing = await readdir(target); }
  catch (error) { if (error.code !== 'ENOENT') throw error; existing = []; }
  const unexpected = existing.filter(name => !names.includes(name));
  if (check && unexpected.length) throw new Error(`client_bundle_extra: ${unexpected.join(', ')}`);
  if (!check) {
    await mkdir(target, { recursive: true });
    for (const name of unexpected) await rm(join(target, name), { recursive: true, force: true });
  }
  for (const name of names) {
    const expected = Buffer.concat([Buffer.from(banner), await readFile(join(source, name))]);
    if (check) {
      let actual;
      try { actual = await readFile(join(target, name)); }
      catch (error) { if (error.code !== 'ENOENT') throw error; }
      if (!actual?.equals(expected)) throw new Error(`client_bundle_stale: ${name}; run node integrations/client/bundle.mjs`);
    } else await writeFile(join(target, name), expected);
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    if (process.argv.slice(2).some(arg => arg !== '--check')) throw new Error('unexpected_arguments');
    await bundleClient({ check: process.argv.includes('--check') });
    console.log('Client bundle matches shared source.');
  } catch (error) { console.error(error.message); process.exitCode = 1; }
}
