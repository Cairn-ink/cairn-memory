import { existsSync, readFileSync, writeFileSync } from 'node:fs';

const generated = new URL('../src/capture/generated/prompts.mjs', import.meta.url);
const readPrompt = (name) => readFileSync(new URL(`../prompts/${name}.md`, import.meta.url), 'utf8');
const shared = readPrompt('qualify-candidates-shared').trimEnd();
const wrapper = readPrompt('qualify-candidates').trimEnd();
const pool = readPrompt('qualify-candidates-pool').trimEnd();
const prompts = {
  EXTRACT_RETAINED_SOURCES_PROMPT: readPrompt('extract-retained-sources'),
  EXTRACT_SOURCE_WINDOWS_PROMPT: readPrompt('extract-source-windows'),
  QUALIFY_MEMORIES_PROMPT: readPrompt('qualify-memories'),
  RECONCILE_MEMORIES_PROMPT: readPrompt('reconcile-memories'),
  QUALIFY_CANDIDATES_INLINE_PROMPT: `${shared}\n\n${wrapper}`,
  QUALIFY_CANDIDATES_SHARED_PROMPT: shared,
  QUALIFY_CANDIDATES_POOL_PROMPT: `${shared}\n\n${pool}`,
};
const source = Buffer.from('// Generated by scripts/generate-capture-prompts.mjs.\n' +
  Object.entries(prompts).map(([name, prompt]) => `export const ${name} = ${JSON.stringify(prompt)};\n`).join(''));

if (process.argv.includes('--check')) {
  if (!existsSync(generated) || !readFileSync(generated).equals(source)) {
    console.error('Generated capture prompts are stale. Run packages/core/scripts/generate-capture-prompts.mjs.');
    process.exitCode = 1;
  }
} else {
  writeFileSync(generated, source);
}
