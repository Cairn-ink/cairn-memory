import { existsSync, readFileSync, writeFileSync } from 'node:fs';

const markdown = new URL('../prompts/relate-rationale.md', import.meta.url);
const generated = new URL('../src/rationale/generated/prompt.mjs', import.meta.url);
const prompt = readFileSync(markdown, 'utf8');
const source = Buffer.from('// Generated by scripts/generate-rationale-prompt.mjs.\n' +
  `export const RELATE_RATIONALE_PROMPT = ${JSON.stringify(prompt)};\n`);

if (process.argv.includes('--check')) {
  if (!existsSync(generated) || !readFileSync(generated).equals(source)) {
    console.error('Generated rationale prompt is stale. Run packages/core/scripts/generate-rationale-prompt.mjs.');
    process.exitCode = 1;
  }
} else {
  writeFileSync(generated, source);
}
