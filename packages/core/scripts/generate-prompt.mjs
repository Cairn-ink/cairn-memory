import { existsSync, readFileSync, writeFileSync } from 'node:fs';

const markdown = new URL('../prompts/extract-memories.md', import.meta.url);
const generated = new URL('../src/extraction/generated/extract-memories-prompt.mjs', import.meta.url);
const prompt = readFileSync(markdown, 'utf8');
const source = Buffer.from('// Generated by scripts/generate.mjs.\n' +
  `export const EXTRACT_MEMORIES_PROMPT = ${JSON.stringify(prompt)};\n`);

if (process.argv.includes('--check')) {
  if (!existsSync(generated) || !readFileSync(generated).equals(source)) {
    console.error('Generated extraction prompt is stale. Run packages/core/scripts/generate.mjs.');
    process.exitCode = 1;
  }
} else {
  writeFileSync(generated, source);
}
