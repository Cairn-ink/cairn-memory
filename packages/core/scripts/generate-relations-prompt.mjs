import { existsSync, readFileSync, writeFileSync } from 'node:fs';

const markdown = new URL('../prompts/judge-memory-relations.md', import.meta.url);
const generated = new URL('../src/relations/generated/prompt.mjs', import.meta.url);
const prompt = readFileSync(markdown, 'utf8');
const source = Buffer.from('// Generated by scripts/generate-relations-prompt.mjs.\n' +
  `export const JUDGE_MEMORY_RELATIONS_PROMPT = ${JSON.stringify(prompt)};\n`);

if (process.argv.includes('--check')) {
  if (!existsSync(generated) || !readFileSync(generated).equals(source)) {
    console.error('Generated relations prompt is stale. Run packages/core/scripts/generate-relations-prompt.mjs.');
    process.exitCode = 1;
  }
} else {
  writeFileSync(generated, source);
}
