const ids = i => ({ path: `src/synthetic/unit-${i}/entry.mjs`, sha: hash(`synthetic-commit-${i}`), error: `E_SYNTH_${String(i).padStart(4, '0')}`, flag: `--synthetic-unit-${i}` });
export function generate() {
  const documents = [];
  const queries = [];
  function query(language, kind, index, text, fact, masks, negative = false) {
    queries.push({ id: `${language}-${kind}-${index}`, language, text, fact, masks, negative, control: false });
  }
  for (let i = 0; i < 800; i++) {
    const noun = nouns[Math.floor(i / 20)], place = places[i % 20], language = i % 2 ? 'zh' : 'en';
    const fact = `stored-${i}`, identifiers = ids(i);
    const prose = language === 'en' ? `Store the ${noun[0]} at the ${place[0]}. Inspect this assigned object weekly.`
      : `將${noun[1]}存放於${place[1]}，每週檢查這項指定物品。`;
    const text = `${prose}\n${Object.values(identifiers).join(' ')}`;
    documents.push({ id: `memory-${i}`, type: 'memory', namespace: namespace(i % 4), fact, text, language, minWorld: 1112, intents: ['current', 'history'], revision: 1 });
    if (i < 384) documents.push({ id: `card-${i}`, type: 'card', namespace: namespace((i + 1) % 4), fact, text, language, minWorld: i < 128 ? 1112 : 3336, intents: ['current', 'history'], revision: 2, bodyRevision: 1 });
    const en = `Find the ${noun[3]} beside the ${place[3]}.`;
    const zh = `${place[1]}的${noun[1]}應該存放在哪裡？`;
    query('en', language === 'zh' ? 'cross' : 'paraphrase', i, en, fact,
      language === 'zh' ? ['cross-en-zh', 'paraphrase'] : ['paraphrase']);
    query('zh', language === 'en' ? 'cross' : 'baseline', i, zh, fact, language === 'en' ? ['cross-zh-en'] : ['baseline']);
    query('zh', 'short', i, noun[1] + place[1], fact, ['short-cjk']);
    query('ja', 'short', i, noun[2] + place[2], fact, ['short-cjk']);
    query('mixed', 'switch', i, `請找 ${place[0]} 的${noun[1]} storage assignment`, fact, ['code-switch']);
    // Category cases are disjoint: 200 distinct positives per language/category.
    const category = IDENTIFIERS[Math.floor(i / 200)];
    for (const lang of LANGUAGES) {
      const prefix = { en: 'Locate', zh: '尋找', ja: '検索', mixed: '請 locate' }[lang];
      query(lang, category, i, `${prefix} ${identifiers[category]}`, fact, ['exact-identifier', `identifier-${category}`]);
    }
  }
  // Baseline exact terms in all languages; no identifier shortcut is added.
  for (const language of LANGUAGES) for (let i = 0; i < 50; i++) {
    const noun = nouns[Math.floor(i / 20)], place = places[i % 20];
    const text = { en: `${noun[0]} ${place[0]}`, zh: `${noun[1]} ${place[1]}`, ja: `${place[2]}の${noun[2]}はどこに保管されますか`, mixed: `${noun[1]} ${place[0]}` }[language];
    query(language, 'baseline-extra', i, text, `stored-${i}`, ['baseline']);
  }
  // The query's semantic key is absent from the authored world. Negatives stay
  // scheduled and retain every return, but never enter positive denominators.
  for (const language of LANGUAGES) {
    const masks = [...new Set(queries.filter(q => q.language === language).flatMap(q => q.masks))];
    for (const mask of masks) for (let i = 0; i < 10; i++) {
      const prefix = { en: 'Unassigned lunar sundial', zh: '未分配的月面日晷', ja: '未割当の月面日時計', mixed: '未分配 lunar sundial' }[language];
      let text = `${prefix} ${mask} ${i}`;
      if (mask === 'short-cjk') text = ['月晷','星晷','日晷','夜晷','雲晷','霧晷','雨晷','雪晷','風晷','虹晷'][i];
      if (mask === 'cross-zh-en') text = `月面第${i}號日晷在哪裡？`;
      if (mask.startsWith('identifier-')) text += ` ${ { path: `src/absent-${i}.mjs`, sha: hash(`absent-${i}`), error: `E_ABSENT_${i}`, flag: `--absent-${i}` }[mask.slice(11)]}`;
      query(language, `negative-${mask}`, i, text, null, [mask, ...(mask.startsWith('identifier-') ? ['exact-identifier'] : [])], true);
    }
  }
  queries.push({ id: 'zh-single-han-control', language: 'zh', text: '中', fact: 'han-control', masks: ['single-han-control'], negative: false, control: true });
  for (let i = 800; i < 3336; i++) documents.push({ id: `memory-${i}`, type: 'memory', namespace: namespace(i % 4), fact: i === 800 ? 'han-control' : `distractor-${i}`,
    text: i === 800 ? '中文手冊保持乾燥。' : `Synthetic unrelated inventory ${i}: sediment sample ${hash(`${SEED}:${i}`).slice(0, 16)} remains sealed.`,
    language: i === 800 ? 'zh' : 'en', minWorld: i < 1112 ? 1112 : 3336, intents: ['current', 'history'], revision: 1 });
  return { version: 'p2e-synthetic-v1', seed: SEED, documents, queries };
}
export function eligible(document, cell) {
  return document.minWorld <= cell.world && cell.types.includes(document.type) && document.intents.includes(cell.intent);
}
export function gold(fixture, query, cell) {
  return fixture.documents.filter(d => eligible(d, cell) && d.fact === query.fact).map(d => d.id).sort();
}
export function deriveLabels(fixture) {
  return cells().map(cell => ({ cell: cell.id, queries: fixture.queries.filter(q => q.language === cell.language).map(q => ({ id: q.id, relevant: gold(fixture, q, cell) })) }));
}
export function validateFixtures(fixture, labels) {
  if (json(fixture) !== json(generate()) || json(labels) !== json(deriveLabels(fixture))) throw Error('fixture_recipe_or_gold_mismatch');
  const docs = new Map(fixture.documents.map(d => [d.id, d]));
  for (const q of fixture.queries) {
    if (q.masks.includes('short-cjk') && !/^[\p{Script=Han}]{2,4}$/u.test(q.text)) throw Error('short_cjk_membership');
    if (q.masks.includes('code-switch') && !(/\p{Script=Han}/u.test(q.text) && /[a-z]/i.test(q.text))) throw Error('mixed_membership');
    if (q.masks.includes('paraphrase') && !q.negative) {
      const terms = new Set(tokenizeT1(q.text));
      for (const d of fixture.documents.filter(d => d.fact === q.fact)) if (tokenizeT1(d.text).some(t => terms.has(t))) throw Error(`paraphrase_token_overlap:${q.id}`);
    }
    for (const direction of ['cross-zh-en', 'cross-en-zh']) if (q.masks.includes(direction) && !q.negative) {
      const expected = direction === 'cross-zh-en' ? 'en' : 'zh';
      if (fixture.documents.filter(d => d.fact === q.fact).some(d => d.language !== expected)) throw Error('cross_direction_membership');
    }
  }
  for (const row of labels) for (const q of row.queries) for (const id of q.relevant) if (!docs.has(id)) throw Error('unknown_gold');
  return { documents: fixture.documents.length, queries: fixture.queries.length, cells: cells().length };
}
export function loadFixtures() {
  const fixture = JSON.parse(readFileSync(new URL('corpus-queries.json', ROOT)));
  const labels = JSON.parse(readFileSync(new URL('labels.json', ROOT)));
  validateFixtures(fixture, labels);
  return { fixture, labels };
}
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  if (process.argv[2] !== '--write') throw Error('explicit_write_required');
  const fixture = generate(), labels = deriveLabels(fixture);
  const counts = validateFixtures(fixture, labels);
  mkdirSync(fileURLToPath(ROOT), { recursive: true });
  writeFileSync(new URL('corpus-queries.json', ROOT), json(fixture));
  writeFileSync(new URL('labels.json', ROOT), json(labels));
  console.log(JSON.stringify(counts));
}
