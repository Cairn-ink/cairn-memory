// Authoritative research constants are immutable at every nesting level;
// public configuration/profile results are separate structured snapshots.
export function deepFreeze(value) {
  if (value && typeof value === 'object' && !Object.isFrozen(value)) {
    for (const child of Object.values(value)) deepFreeze(child);
    Object.freeze(value);
  }
  return value;
}
