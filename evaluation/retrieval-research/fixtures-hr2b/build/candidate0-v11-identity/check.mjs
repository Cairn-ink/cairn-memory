// Coordinator's identity check for the HR-2b candidate-0 re-render (protocol v1.1 §9).
// Usage (from the repository root): node <this file> <baselineCommit> [fixtureDir]
// Compares the re-rendered fixture in the working tree with the committed candidate-0 v1 files:
//   1. hr1-facts.json: every fact field, the families and the forbidden lexicon (byte identity first);
//   2. build/world-stats.json generation.placementAllocation (per-fact placement);
//   3. the fact-to-memory plan: per memory in array order, the sorted expressed fact ids with body/span;
//   4. hr1-facts-view.json regenerated by tools/facts-view.mjs, byte-identical to the baseline file.
// Exit 0 only when all four hold. Independent of W1's own comparison script.
import { execFileSync } from 'node:child_process';
import { readFileSync, mkdtempSync } from 'node:fs';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { createHash } from 'node:crypto';
const [baseline, fixtureDir = 'evaluation/retrieval-research/fixtures-hr2b'] = process.argv.slice(2);
if (!baseline) { console.error('usage: node hr2b-identity-check.mjs <baselineCommit> [fixtureDir]'); process.exit(2); }
const sha = text => createHash('sha256').update(text).digest('hex');
const show = name => execFileSync('git', ['show', `${baseline}:${fixtureDir}/${name}`], { encoding: 'utf8', maxBuffer: 1 << 28 });
const read = name => readFileSync(join(fixtureDir, name), 'utf8');
const results = [];
const check = (name, ok, detail) => { results.push({ check: name, ok, detail }); };
// 1. facts
const baseFactsText = show('hr1-facts.json'), newFactsText = read('hr1-facts.json');
check('facts_bytes_identical', baseFactsText === newFactsText, { baseline: sha(baseFactsText), rerender: sha(newFactsText) });
const baseFacts = JSON.parse(baseFactsText), newFacts = JSON.parse(newFactsText);
const factKey = f => JSON.stringify(f);
const baseById = new Map(baseFacts.facts.map(f => [f.id, factKey(f)])), newById = new Map(newFacts.facts.map(f => [f.id, factKey(f)]));
const factDiffs = [...new Set([...baseById.keys(), ...newById.keys()])].filter(id => baseById.get(id) !== newById.get(id));
check('facts_fields_identical', factDiffs.length === 0 && baseFacts.facts.length === newFacts.facts.length, { facts: newFacts.facts.length, differing: factDiffs.slice(0, 20) });
check('families_identical', JSON.stringify(baseFacts.families) === JSON.stringify(newFacts.families), { families: newFacts.families?.length });
check('lexicon_identical', JSON.stringify(baseFacts.forbiddenLexicon) === JSON.stringify(newFacts.forbiddenLexicon), {});
const coverage = facts => Object.fromEntries(facts.facts.map(f => [f.id, f.coverage ?? 'absent']));
check('coverage_identical', JSON.stringify(coverage(baseFacts)) === JSON.stringify(coverage(newFacts)), {});
// 2. placement allocation
const baseStats = JSON.parse(show('build/world-stats.json')), newStats = JSON.parse(read('build/world-stats.json'));
const alloc = s => JSON.stringify(Object.entries(s.generation.placementAllocation).sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0));
check('placement_allocation_identical', alloc(baseStats) === alloc(newStats), { entries: Object.keys(newStats.generation.placementAllocation).length, seed: [baseStats.generation.seed, newStats.generation.seed] });
// 3. fact-to-memory plan
const baseCorpus = JSON.parse(show('hr1-corpus.json')), newCorpus = JSON.parse(read('hr1-corpus.json'));
const plan = c => c.memories.map(m => ({ ns: m.namespace, scale: m.scale, family: m.expresses.length ? baseFacts.facts.find(f => f.id === m.expresses[0].fact)?.family ?? null : null,
  facts: m.expresses.map(e => `${e.fact}:${e.where}`).sort() }));
const basePlan = plan(baseCorpus), newPlan = plan(newCorpus);
const planDiffs = basePlan.map((row, i) => JSON.stringify(row) === JSON.stringify(newPlan[i]) ? null : i).filter(i => i !== null);
check('fact_to_memory_plan_identical', basePlan.length === newPlan.length && planDiffs.length === 0, { memories: newPlan.length, differingIndexes: planDiffs.slice(0, 20) });
const receiptMax = Math.max(...newCorpus.memories.map(m => m.spans.length));
check('receipts_at_most_four', receiptMax <= 4, { maxReceipts: receiptMax, baselineMax: Math.max(...baseCorpus.memories.map(m => m.spans.length)) });
// 4. facts view
const out = join(mkdtempSync(join(tmpdir(), 'hr2b-identity-')), 'facts-view.json');
execFileSync(process.execPath, ['evaluation/retrieval-research/tools/facts-view.mjs', '--fixture', fixtureDir, '--out', out], { stdio: ['ignore', 'ignore', 'inherit'] });
const baseView = show('hr1-facts-view.json'), newView = readFileSync(out, 'utf8');
check('facts_view_bytes_identical', baseView === newView, { baseline: sha(baseView), regenerated: sha(newView) });
const ok = results.every(r => r.ok);
console.log(JSON.stringify({ ok, baseline, fixtureDir, results }, null, 2));
process.exit(ok ? 0 : 1);
