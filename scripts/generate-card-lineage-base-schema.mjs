import { readFileSync,writeFileSync } from 'node:fs';
import { openDatabase } from '../core/database.mjs';

// Freeze the inherited declarations independently of the lineage installer.
// Synthetic in-memory stores only; no serving file is opened by this generator.
const bases={},extendedReceipts={};
for(const base of [23,33]) {
  const db=openDatabase(':memory:',base===23?{privateCards:true}:{currentDependencies:true});
  try {
    bases[base]=db.prepare('SELECT type,name,sql FROM sqlite_schema WHERE sql IS NOT NULL ORDER BY type,name').all();
    db.exec('ALTER TABLE receipts ADD COLUMN occurred_at TEXT');
    extendedReceipts[base]=db.prepare("SELECT sql FROM sqlite_schema WHERE name='receipts'").get().sql;
  } finally {db.close();}
}
const target=new URL('../core/card-lineage-base-schema.mjs',import.meta.url),declarations=
  '// Generated by scripts/generate-card-lineage-base-schema.mjs from pristine base installers.\n'+
  'export const lineageBaseDeclarations = '+JSON.stringify(bases,null,2)+';\n'+
  'export const extendedReceiptDeclarations = '+JSON.stringify(extendedReceipts,null,2)+';\n';
if(process.argv.includes('--check')) {
  if(readFileSync(target,'utf8')!==declarations)throw Error('lineage_base_schema_stale');
} else writeFileSync(target,declarations);
console.log(JSON.stringify(Object.fromEntries(Object.entries(bases).map(([base,rows])=>[base,rows.length]))));
